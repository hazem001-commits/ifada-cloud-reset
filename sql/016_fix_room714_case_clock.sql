-- ============================================================
-- IFADA — 016_fix_room714_case_clock.sql
-- إرجاع الساعة الداخلية لغرفة 714 لقيمتها الأصلية.
--
-- المشكلة (مُثبتة من رد case_clock الحقيقي أثناء QA بالمتصفح):
--   start_ck = 1499, multiplier = 1, started_at صحيح (لحظة البدء).
-- يعني الجلسة كانت تبدأ على 00:59 داخل القضية بدل 23:00، وأدلة
-- المراقبة D-02 / D-03 / D-04 (expires_ck = 1500) كانت تنتهي
-- بعد أقل من دقيقة من بداية التحقيق.
--
-- السبب: صف case_config لغرفة 714 بقاعدة البيانات الحية انحرف عن
-- القيمة الأصلية بـ 011_seed_automation_room714.sql (start_ck = 1380).
-- ما في أي ملف بالمشروع بيكتب 1499 — غالباً تعديل يدوي قديم لاختبار
-- انتهاء الصلاحية. منطق case_clock نفسه (timestamptz، now()،
-- started_at = now() بـ start_session) سليم وما بيتغير هون.
--          
-- ما بنلمس expires_ck ولا توقيت الأدلة — بس بنرجّع قيمة البداية.
--       
-- ملاحظة: case_clock بتحسب الوقت لحظياً من case_config، فالتصحيح
-- بينطبق فوراً على كل جلسات غرفة 714 — بما فيها الجلسات النشطة
-- حالياً (ساعتها بترجع لـ 23:00 + الوقت الحقيقي المنقضي منذ البدء).
-- ============================================================

update public.case_config
set start_ck = 1380
where case_id = 'room-714'
  and start_ck is distinct from 1380;

-- تحقق (قراءة فقط): المتوقع start_ck = 1380, multiplier = 1
select case_id, start_ck, multiplier
from public.case_config
where case_id = 'room-714';
